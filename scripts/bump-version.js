import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const rootDir = path.resolve(__dirname, '..');

// 1. Read package.json
const pkgPath = path.join(rootDir, 'package.json');
const pkg = JSON.parse(fs.readFileSync(pkgPath, 'utf8'));
const currentVersion = pkg.version;

// Parse version: major.minor.patch
const parts = currentVersion.split('.').map(num => parseInt(num, 10));
if (parts.length !== 3 || parts.some(isNaN)) {
  console.error(`Invalid current version: ${currentVersion}`);
  process.exit(1);
}

const bumpType = process.argv[2] || 'patch';
let newVersion;

if (bumpType === 'major') {
  newVersion = `${parts[0] + 1}.0.0`;
} else if (bumpType === 'minor') {
  newVersion = `${parts[0]}.${parts[1] + 1}.0`;
} else if (bumpType === 'patch') {
  newVersion = `${parts[0]}.${parts[1]}.${parts[2] + 1}`;
} else if (/^\d+\.\d+\.\d+$/.test(bumpType)) {
  newVersion = bumpType;
} else {
  console.error(`Unknown bump type: ${bumpType}. Use patch, minor, major, or explicit X.Y.Z`);
  process.exit(1);
}

console.log(`\n========================================`);
console.log(`🚀 Bumping version: ${currentVersion} -> ${newVersion}`);
console.log(`========================================\n`);

// 2. Update package.json
pkg.version = newVersion;
fs.writeFileSync(pkgPath, JSON.stringify(pkg, null, 2) + '\n', 'utf8');
console.log(`✔ Updated package.json: ${newVersion}`);

// 3. Update src-tauri/tauri.conf.json
const tauriConfPath = path.join(rootDir, 'src-tauri', 'tauri.conf.json');
if (fs.existsSync(tauriConfPath)) {
  const tauriConf = JSON.parse(fs.readFileSync(tauriConfPath, 'utf8'));
  tauriConf.version = newVersion;
  fs.writeFileSync(tauriConfPath, JSON.stringify(tauriConf, null, 2) + '\n', 'utf8');
  console.log(`✔ Updated src-tauri/tauri.conf.json: ${newVersion}`);
}

// 4. Update src-tauri/Cargo.toml
const cargoTomlPath = path.join(rootDir, 'src-tauri', 'Cargo.toml');
if (fs.existsSync(cargoTomlPath)) {
  let cargoToml = fs.readFileSync(cargoTomlPath, 'utf8');
  cargoToml = cargoToml.replace(
    /(\[package\][\s\S]*?version\s*=\s*")[^"]+(")/,
    `$1${newVersion}$2`
  );
  fs.writeFileSync(cargoTomlPath, cargoToml, 'utf8');
  console.log(`✔ Updated src-tauri/Cargo.toml: ${newVersion}`);
}

// 5. Update src/renderer/version.ts
const versionTsPath = path.join(rootDir, 'src', 'renderer', 'version.ts');
const versionTsContent = `// Auto-generated by scripts/bump-version.js. Do not edit directly.\nexport const APP_VERSION = '${newVersion}';\n`;
fs.writeFileSync(versionTsPath, versionTsContent, 'utf8');
console.log(`✔ Updated src/renderer/version.ts: ${newVersion}\n`);
